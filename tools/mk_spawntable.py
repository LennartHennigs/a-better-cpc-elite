#!/usr/bin/env python3
"""Writes src/elite128/spawn_table.inc: the 27 orientations of the 128K asteroid spawn (src/elite128/spawnmod.asm, docs/_ship_spawning.md).

usage: python3 -I tools/mk_spawntable.py
Row idx = tx * 9 + ty * 3 + tz, each trit 0 = negative, 1 = zero, 2 = positive: the direction the rock flies in (nosev), its components rounded to -1, 0, 1 and normalised, so 26
directions (the faces, edges and corners of a cube) and the unused middle row, which repeats the stock orientation. Per row nine bytes: the high bytes of nosev, roofv and sidev (x, y, z each),
sign-magnitude (bit 7 = minus) with 1.0 = &7F, the engine's scale (shipEntityInitMatrixdata: nosev (0, 0, -1) = &FF in z, roofv (0, 1, 0), sidev (-1, 0, 0)). roofv is the world y axis
made perpendicular to nosev (the world z axis when nosev is vertical), sidev = roofv x nosev, so every row is an exact orthonormal frame before rounding; the engine's per-frame tidy does the rest.
"""
import itertools
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/elite128/spawn_table.inc"


def unit(v):
    n = math.sqrt(sum(c * c for c in v))
    return [c / n for c in v]


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def enc(c):
    m = min(127, int(round(abs(c) * 127)))
    return m | (0x80 if c < 0 and m else 0)


def row(t):
    n = [x - 1 for x in t]
    if n == [0, 0, 0]:
        n = [0, 0, -1]
    n = unit(n)
    up = [0, 1, 0] if abs(n[1]) < 0.99 else [0, 0, 1]
    d = sum(u * c for u, c in zip(up, n))
    r = unit([u - d * c for u, c in zip(up, n)])
    s = cross(r, n)
    return [enc(c) for c in n + r + s]


def main():
    lines = ["; generated by tools/mk_spawntable.py: do not edit. 27 rows of 9 bytes (nosev, roofv, sidev: x, y, z high bytes), row = tx * 9 + ty * 3 + tz (trit 0 negative, 1 zero, 2 positive)"]
    for t in itertools.product(range(3), repeat=3):
        r = row(t)
        lines.append("    db " + ",".join(f"0x{b:02X}" for b in r) + f"    ; {t[0] * 9 + t[1] * 3 + t[2]:2d}: direction ({t[0] - 1:+d}, {t[1] - 1:+d}, {t[2] - 1:+d})")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT}: 27 rows")


main()
